"""Build the static dashboard from the engine's real output.

    python demo/build.py                  # writes demo/dist/
    python demo/build.py --out /some/dir  # writes there instead

Runs the certification engine on examples/data, writes data/report.json and
data.js (the same JSON assigned to window.CERT_REPORT so the page also works from
file://), and copies the hand-written HTML, CSS, and JS. No network, no CDN.
"""

from __future__ import annotations

import argparse
import json
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from partner_cert import evaluate, load_dataset  # noqa: E402
from partner_cert.report import to_dict  # noqa: E402

SRC = Path(__file__).resolve().parent / "src"


def build(out: Path, data_dir: Path) -> dict:
    report = to_dict(evaluate(load_dataset(data_dir)))
    if out.exists():
        shutil.rmtree(out)
    (out / "data").mkdir(parents=True)
    payload = json.dumps(report, indent=2)
    (out / "data" / "report.json").write_text(payload + "\n", encoding="utf-8")
    (out / "data.js").write_text(
        "/* Generated by demo/build.py from partner-cert output. Do not edit. */\n"
        f"window.CERT_REPORT = {payload};\n",
        encoding="utf-8",
    )
    for name in ("index.html", "styles.css", "app.js"):
        shutil.copy2(SRC / name, out / name)
    return report


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description="Build the static readiness dashboard.")
    p.add_argument("--out", type=Path, default=ROOT / "demo" / "dist")
    p.add_argument("--data", type=Path, default=ROOT / "examples" / "data")
    args = p.parse_args(argv)
    report = build(args.out, args.data)
    s = report["summary"]
    print(
        f"built {args.out} ({s['partners']} partners, {s['models']} models, "
        f"{s['certified_pct']}% certified)"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
